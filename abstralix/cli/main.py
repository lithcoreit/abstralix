@plugins_app.command("list")
def plugins_list():
    """List all loaded plugins across all 6 categories."""
    reg = PluginRegistry()
    table = Table(title="Installed Abstralix 0.5.0 Plugins", show_lines=False)
    table.add_column("Category", style="cyan")
    table.add_column("Identifier", style="bold white")
    table.add_column("Class", style="dim green")

    categories = [
        ("Object", reg.objects),
        ("Attribute", reg.attributes),
        ("Type", reg.types),
        ("Function", reg.functions),
        ("Provider", reg.providers),
        ("Language", reg.languages),
    ]

    for cat_name, registry_dict in categories:
        for k, v in registry_dict.items():
            table.add_row(cat_name, str(k), v.__class__.__name__)

    console.print(table)

