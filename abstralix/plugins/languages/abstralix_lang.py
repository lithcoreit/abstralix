from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple
from abstralix import __version__
from abstralix.plugins.languages.base import BaseLanguagePlugin


class AbstralixLanguagePlugin(BaseLanguagePlugin):
    language_id = "abstralix"

    def build_prompt(
        self, void_name: str, attributes: Dict[str, Any], dependencies_info: List[Dict[str, Any]], error_feedback: Optional[str] = None
    ) -> List[Dict[str, str]]:
        sys_prompt = (
            f"You are an Abstralix {__version__} architecture generator. "
            "Generate valid .abx syntax: folder name { ... }, file name.py { void fn { @in = {} @out = {} } }. "
            "Return ONLY raw .abx code without markdown blocks."
        )
        task = attributes.get("@context", "")
        return [
            {"role": "system", "content": sys_prompt},
            {"role": "user", "content": f"Void target: {void_name}\nGenerate architecture task: {task}"},
        ]

    def check_syntax(self, code: str, void_name: str) -> Tuple[bool, Optional[str]]:
        try:
            from abstralix.core.lexer import Lexer
            from abstralix.core.parser import Parser

            tokens = Lexer(code, "<generated.abx>").tokenize()
            Parser(tokens, "<generated.abx>").parse()
            return True, None
        except Exception as exc:
            return False, f"Invalid Abstralix syntax: {exc}"

    def assemble_file(
        self, file_attributes: Dict[str, Any], voids_code: List[str], cross_file_imports: List[Tuple[str, str]]
    ) -> str:
        body = "\n\n".join(v.strip() for v in voids_code)
        return f"// Generated by Abstralix {__version__}\n\n{body}"

    async def run_invariant_test(
        self, sandbox_root: Path, rel_file_path: Path, void_name: str, invariant_code: str
    ) -> Tuple[bool, Optional[str]]:
        return True, None

    def build_auto_invariant_prompt(self, void_name: str, attributes: Dict[str, Any]) -> List[Dict[str, str]]:
        return [{"role": "system", "content": "Test ABX"}, {"role": "user", "content": f"Test {void_name}"}]
