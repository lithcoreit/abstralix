import ast
import asyncio
import sys
import textwrap
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple

from abstralix import __version__
from abstralix.plugins.languages.base import BaseLanguagePlugin


def _format_py_signature(func_name: str, in_params: Dict[str, str], out_params: Dict[str, str]) -> str:
    args_sig = ", ".join(f"{k}: {v}" for k, v in in_params.items())
    if len(out_params) == 1:
        ret_type = list(out_params.values())[0]
    elif len(out_params) > 1:
        ret_type = "dict"
    else:
        ret_type = "None"
    return f"def {func_name}({args_sig}) -> {ret_type}:"


class PythonLanguagePlugin(BaseLanguagePlugin):
    language_id = "python"

    def build_prompt(
        self,
        void_name: str,
        attributes: Dict[str, Any],
        dependencies_info: List[Dict[str, Any]],
        error_feedback: Optional[str] = None,
    ) -> List[Dict[str, str]]:
        in_params: Dict[str, str] = attributes.get("@in") or {}
        out_params: Dict[str, str] = attributes.get("@out") or {}
        libs: List[str] = attributes.get("@lib") or []
        context_text: str = textwrap.dedent(attributes.get("@context") or "").strip()
        inject_code: bool = bool(attributes.get("@inject_code", False))

        sig_line = _format_py_signature(void_name, in_params, out_params)

        sys_prompt = (
            f"You are an isolated Python function generator for Abstralix {__version__}.\n"
            "Write ONLY valid Python code for the requested function.\n"
            "Do NOT wrap code in markdown blocks, do NOT add explanations or test calls outside the function.\n"
            f"The function MUST be named '{void_name}' and match the exact parameter names."
        )

        user_lines = [
            f"Target Function Signature:\n{sig_line}",
            f"Task Description:\n{context_text}",
        ]

        if len(out_params) == 1:
            only_type = list(out_params.values())[0]
            user_lines.append(
                f"Return Rule: Return a single value of type '{only_type}' directly (do NOT wrap it in a dict)."
            )
        elif len(out_params) > 1:
            user_lines.append(
                f"Return Rule: Return a Python dict with exact keys: {out_params}"
            )

        if libs:
            libs_str = ", ".join(libs)
            user_lines.append(f"Allowed / Imported Libraries: {libs_str}")

        if dependencies_info:
            user_lines.append("Available Helper Functions:")
            for dep in dependencies_info:
                dep_sig = _format_py_signature(dep["name"], dep.get("in") or {}, dep.get("out") or {})
                user_lines.append(f"- {dep_sig}  # {dep['info']}")
                if inject_code and dep.get("code"):
                    user_lines.append(f"  Implementation:\n{dep['code']}")

        if error_feedback:
            user_lines.append(f"\n--- PREVIOUS ATTEMPT FAILED ---\n{error_feedback}")

        return [
            {"role": "system", "content": sys_prompt},
            {"role": "user", "content": "\n".join(user_lines)},
        ]

    def check_syntax(self, code: str, void_name: str) -> Tuple[bool, Optional[str]]:
        try:
            tree = ast.parse(code)
        except SyntaxError as exc:
            return False, f"SyntaxError: {exc.msg} at line {exc.lineno}:\n{exc.text}"

        defined_funcs = [
            node.name for node in ast.walk(tree)
            if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef))
        ]
        if void_name not in defined_funcs:
            return False, f"Expected function 'def {void_name}(...)', found: {defined_funcs}"
        return True, None

    def assemble_file(
        self,
        file_attributes: Dict[str, Any],
        voids_code: List[str],
        cross_file_imports: List[Tuple[str, str]],
    ) -> str:
        header_imports: List[str] = []
        seen = set()

        libs = file_attributes.get("@lib") or []
        for lib in libs:
            pkg = lib.split(".")[0].strip()
            if pkg and pkg not in seen:
                header_imports.append(f"import {pkg}")
                seen.add(pkg)

        for mod_path, func_name in cross_file_imports:
            imp = f"from {mod_path} import {func_name}"
            if imp not in seen:
                header_imports.append(imp)
                seen.add(imp)

        cleaned_voids: List[str] = []
        for block in voids_code:
            lines = [l for l in block.strip().splitlines() if not (l.strip().startswith(("import ", "from ")) and not l.startswith((" ", "\t")))]
            cleaned_voids.append("\n".join(lines).strip())

        lines = [f"# Generated by Abstralix {__version__}"] + header_imports + [""]
        for block in cleaned_voids:
            lines.append(block)
            lines.append("")

        return "\n".join(lines)

    async def run_invariant_test(
        self, sandbox_root: Path, rel_file_path: Path, void_name: str, invariant_code: str
    ) -> Tuple[bool, Optional[str]]:
        runner_file = sandbox_root / f"_abx_test_{void_name}.py"
        module_rel = rel_file_path.with_suffix("")
        module_import = ".".join(module_rel.parts)

        clean_inv = textwrap.dedent(invariant_code).strip()
        indented_inv = "\n".join("    " + line for line in clean_inv.splitlines())

        runner_script = (
            "import sys\n"
            "import inspect\n"
            "import traceback\n"
            f"sys.path.insert(0, {str(sandbox_root)!r})\n"
            f"from {module_import} import {void_name} as _target_fn\n\n"
            "class _CompleteSignal(Exception): pass\n"
            "class _IncompleteSignal(Exception): pass\n\n"
            "def input(*args, **kwargs):\n"
            "    if len(args) == 1 and not kwargs and isinstance(args[0], dict):\n"
            "        sig = set(inspect.signature(_target_fn).parameters.keys())\n"
            "        if set(args[0].keys()).issubset(sig) and len(args[0]) > 0:\n"
            "            return _target_fn(**args[0])\n"
            "    return _target_fn(*args, **kwargs)\n\n"
            "def complete(): raise _CompleteSignal()\n"
            "def incomplete(reason='Test failed'): raise _IncompleteSignal(str(reason))\n\n"
            "def _run():\n"
            f"{indented_inv}\n\n"
            "if __name__ == '__main__':\n"
            "    try:\n"
            "        _run()\n"
            "    except _CompleteSignal:\n"
            "        sys.exit(0)\n"
            "    except _IncompleteSignal as e:\n"
            "        print(f'Invariant failed: {e}', file=sys.stderr)\n"
            "        sys.exit(2)\n"
            "    except Exception:\n"
            "        traceback.print_exc(file=sys.stderr)\n"
            "        sys.exit(1)\n"
        )
        runner_file.write_text(runner_script, encoding="utf-8")
        try:
            proc = await asyncio.create_subprocess_exec(
                sys.executable, str(runner_file), cwd=str(sandbox_root),
                stdout=asyncio.subprocess.PIPE, stderr=asyncio.subprocess.PIPE
            )
            stdout, stderr = await asyncio.wait_for(proc.communicate(), timeout=30.0)
            if proc.returncode == 0:
                return True, None
            err = stderr.decode("utf-8", errors="replace").strip()
            out = stdout.decode("utf-8", errors="replace").strip()
            return False, err or out or f"Exit code {proc.returncode}"
        finally:
            runner_file.unlink(missing_ok=True)

    def build_auto_invariant_prompt(self, void_name: str, attributes: Dict[str, Any]) -> List[Dict[str, str]]:
        in_params = attributes.get("@in") or {}
        out_params = attributes.get("@out") or {}
        context_text = textwrap.dedent(attributes.get("@context") or "").strip()
        sig = _format_py_signature(void_name, in_params, out_params)
        example_args = ", ".join(f"{k}=..." for k in in_params.keys())
        return [
            {"role": "system", "content": f"Write Python test script using input({example_args}) and complete()."},
            {"role": "user", "content": f"Signature: {sig}\nTask: {context_text}"},
        ]