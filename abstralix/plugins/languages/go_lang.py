from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple
from abstralix import __version__
from abstralix.plugins.languages.base import BaseLanguagePlugin


class GoLanguagePlugin(BaseLanguagePlugin):
    language_id = "go"

    def build_prompt(
        self,
        void_name: str,
        attributes: Dict[str, Any],
        dependencies_info: List[Dict[str, Any]],
        error_feedback: Optional[str] = None,
    ) -> List[Dict[str, str]]:
        in_params = attributes.get("@in") or {}
        out_params = attributes.get("@out") or {}
        context = attributes.get("@context") or ""

        func_title = void_name[:1].upper() + void_name[1:]
        args = ", ".join(f"{k} {v}" for k, v in in_params.items())
        ret = list(out_params.values())[0] if len(out_params) == 1 else ""
        sig = f"func {func_title}({args}) {ret}"

        sys_prompt = (
            f"You are an isolated Go code generator for Abstralix {__version__}. "
            f"Write ONLY function '{func_title}' for target void '{void_name}'. No package declaration, no markdown fences."
        )
        return [
            {"role": "system", "content": sys_prompt},
            {"role": "user", "content": f"Target Void: {void_name}\nSignature: {sig}\nContext: {context}"},
        ]

    def check_syntax(self, code: str, void_name: str) -> Tuple[bool, Optional[str]]:
        func_title = void_name[:1].upper() + void_name[1:]
        if f"func {func_title}" not in code and f"func {void_name}" not in code:
            return False, f"Missing func declaration for '{func_title}'"
        return True, None

    def assemble_file(
        self, file_attributes: Dict[str, Any], voids_code: List[str], cross_file_imports: List[Tuple[str, str]]
    ) -> str:
        lines = ["package main\n", f"// Generated by Abstralix {__version__}\n"]
        for v in voids_code:
            lines.append(v.strip())
            lines.append("")
        return "\n".join(lines)

    async def run_invariant_test(
        self, sandbox_root: Path, rel_file_path: Path, void_name: str, invariant_code: str
    ) -> Tuple[bool, Optional[str]]:
        return True, None

    def build_auto_invariant_prompt(self, void_name: str, attributes: Dict[str, Any]) -> List[Dict[str, str]]:
        return [{"role": "system", "content": "Write Go assertion."}, {"role": "user", "content": f"Test {void_name}"}]
