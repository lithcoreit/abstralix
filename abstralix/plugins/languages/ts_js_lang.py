import asyncio
import shutil
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple
from abstralix.plugins.languages.base import BaseLanguagePlugin


class TypeScriptLanguagePlugin(BaseLanguagePlugin):
    language_id = "typescript"

    def build_prompt(
        self,
        void_name: str,
        attributes: Dict[str, Any],
        dependencies_info: List[Dict[str, Any]],
        error_feedback: Optional[str] = None,
    ) -> List[Dict[str, str]]:
        in_params = attributes.get("@in") or {}
        out_params = attributes.get("@out") or {}
        context_text = attributes.get("@context") or ""

        args_sig = ", ".join(f"{k}: {v}" for k, v in in_params.items())
        ret_type = list(out_params.values())[0] if len(out_params) == 1 else "Record<string, any>"
        sig = f"export function {void_name}({args_sig}): {ret_type}"

        sys_prompt = (
            "You are an isolated TypeScript/JavaScript code generator for Abstralix 0.5.0. "
            "Write ONLY clean TypeScript code for the requested exported function. "
            f"Function must be named '{void_name}'. Do not wrap in markdown fences."
        )
        user_lines = [
            f"Signature: {sig}",
            f"Specification (@context): {context_text}",
        ]
        if dependencies_info:
            user_lines.append("Available helper functions in scope:")
            for d in dependencies_info:
                user_lines.append(f"- {d['name']}({d.get('in')}): {d.get('out')} // {d.get('info')}")

        if error_feedback:
            user_lines.append(f"PREVIOUS ATTEMPT FAILED: {error_feedback}")

        return [
            {"role": "system", "content": sys_prompt},
            {"role": "user", "content": "\n".join(user_lines)},
        ]

    def check_syntax(self, code: str, void_name: str) -> Tuple[bool, Optional[str]]:
        if void_name not in code:
            return False, f"Function '{void_name}' not defined in generated code"
        if code.count("{") != code.count("}") or code.count("(") != code.count(")"):
            return False, "Unbalanced braces or parentheses in TypeScript code"
        return True, None

    def assemble_file(
        self,
        file_attributes: Dict[str, Any],
        voids_code: List[str],
        cross_file_imports: List[Tuple[str, str]],
    ) -> str:
        lines = ["// Generated by Abstralix 0.5.0"]
        for mod, fn in cross_file_imports:
            lines.append(f"import {{ {fn} }} from './{mod}';")
        lines.append("")
        for v in voids_code:
            lines.append(v.strip())
            lines.append("")
        return "\n".join(lines)

    async def run_invariant_test(
        self, sandbox_root: Path, rel_file_path: Path, void_name: str, invariant_code: str
    ) -> Tuple[bool, Optional[str]]:
        node_bin = shutil.which("node") or shutil.which("bun")
        if not node_bin:
            return True, None

        runner = sandbox_root / f"_test_{void_name}.js"
        content = (
            f"const target = require('./{rel_file_path.as_posix()}');\n"
            f"function input(args) {{ return target.{void_name}(args); }}\n"
            f"function complete() {{ process.exit(0); }}\n"
            f"function incomplete(msg) {{ console.error('FAIL: ' + msg); process.exit(1); }}\n"
            f"try {{\n{invariant_code}\n}} catch(e) {{ console.error(e); process.exit(1); }}\n"
        )
        runner.write_text(content, encoding="utf-8")
        try:
            proc = await asyncio.create_subprocess_exec(
                node_bin, str(runner), cwd=str(sandbox_root),
                stdout=asyncio.subprocess.PIPE, stderr=asyncio.subprocess.PIPE
            )
            _, stderr = await proc.communicate()
            if proc.returncode == 0:
                return True, None
            return False, stderr.decode("utf-8", errors="replace")
        finally:
            runner.unlink(missing_ok=True)

    def build_auto_invariant_prompt(self, void_name: str, attributes: Dict[str, Any]) -> List[Dict[str, str]]:
        return [
            {"role": "system", "content": "Write JS assertion using input(...) and complete()."},
            {"role": "user", "content": f"Test {void_name}"},
        ]


class JavaScriptLanguagePlugin(TypeScriptLanguagePlugin):
    language_id = "javascript"
