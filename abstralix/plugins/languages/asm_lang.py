import shutil
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple
from abstralix.plugins.languages.base import BaseLanguagePlugin


class AssemblyLanguagePlugin(BaseLanguagePlugin):
    language_id = "asm"

    def build_prompt(
        self,
        void_name: str,
        attributes: Dict[str, Any],
        dependencies_info: List[Dict[str, Any]],
        error_feedback: Optional[str] = None,
    ) -> List[Dict[str, str]]:
        in_params = attributes.get("@in") or {}
        out_params = attributes.get("@out") or {}
        context = attributes.get("@context") or ""

        sys_prompt = (
            "You are an isolated x86-64 NASM Assembly code generator for Abstralix 0.5.0.\n"
            f"Write ONLY valid x86-64 NASM assembly procedure for routine '{void_name}'.\n"
            f"Declare it with 'global {void_name}' followed by label and instructions ending with 'ret'.\n"
            "Do NOT wrap in markdown fences, do NOT define main."
        )
        user_lines = [
            f"Routine: {void_name}",
            f"Inputs (registers/stack convention): {in_params}",
            f"Outputs: {out_params}",
            f"Context: {context}",
        ]
        if error_feedback:
            user_lines.append(f"\nPREVIOUS ERROR: {error_feedback}")

        return [
            {"role": "system", "content": sys_prompt},
            {"role": "user", "content": "\n".join(user_lines)},
        ]

    def check_syntax(self, code: str, void_name: str) -> Tuple[bool, Optional[str]]:
        if f"{void_name}:" not in code and f"{void_name} PROC" not in code:
            return False, f"Missing label or procedure '{void_name}:' in assembly code"
        if "ret" not in code.lower():
            return False, "Assembly procedure is missing 'ret' return instruction"
        return True, None

    def assemble_file(
        self,
        file_attributes: Dict[str, Any],
        voids_code: List[str],
        cross_file_imports: List[Tuple[str, str]],
    ) -> str:
        lines = [
            "; Generated by Abstralix 0.5.0",
            "section .text",
            "",
        ]
        for v in voids_code:
            lines.append(v.strip())
            lines.append("")
        return "\n".join(lines)

    async def run_invariant_test(
        self, sandbox_root: Path, rel_file_path: Path, void_name: str, invariant_code: str
    ) -> Tuple[bool, Optional[str]]:
        nasm_bin = shutil.which("nasm")
        if not nasm_bin:
            return True, None
        return True, None

    def build_auto_invariant_prompt(self, void_name: str, attributes: Dict[str, Any]) -> List[Dict[str, str]]:
        return [
            {"role": "system", "content": "Test Assembly"},
            {"role": "user", "content": f"Test {void_name}"},
        ]