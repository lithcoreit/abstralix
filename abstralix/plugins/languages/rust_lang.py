import asyncio
import shutil
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple
from abstralix.plugins.languages.base import BaseLanguagePlugin


class RustLanguagePlugin(BaseLanguagePlugin):
    language_id = "rust"

    def build_prompt(
        self,
        void_name: str,
        attributes: Dict[str, Any],
        dependencies_info: List[Dict[str, Any]],
        error_feedback: Optional[str] = None,
    ) -> List[Dict[str, str]]:
        in_params = attributes.get("@in") or {}
        out_params = attributes.get("@out") or {}
        context = attributes.get("@context") or ""

        args_sig = ", ".join(f"{k}: {v}" for k, v in in_params.items())
        ret_type = list(out_params.values())[0] if len(out_params) == 1 else "()"
        sig = f"pub fn {void_name}({args_sig}) -> {ret_type}"

        sys_prompt = (
            "You are an isolated Rust code generator for Abstralix 0.5.0. "
            f"Write ONLY valid Rust function 'pub fn {void_name}'. No markdown fences."
        )
        user_lines = [f"Signature: {sig}", f"Context: {context}"]
        if error_feedback:
            user_lines.append(f"PREVIOUS ERROR: {error_feedback}")

        return [
            {"role": "system", "content": sys_prompt},
            {"role": "user", "content": "\n".join(user_lines)},
        ]

    def check_syntax(self, code: str, void_name: str) -> Tuple[bool, Optional[str]]:
        if f"fn {void_name}" not in code:
            return False, f"Missing 'fn {void_name}' definition"
        if code.count("{") != code.count("}"):
            return False, "Unbalanced braces in Rust code"
        return True, None

    def assemble_file(
        self,
        file_attributes: Dict[str, Any],
        voids_code: List[str],
        cross_file_imports: List[Tuple[str, str]],
    ) -> str:
        lines = ["// Generated by Abstralix 0.5.0\n"]
        for v in voids_code:
            lines.append(v.strip())
            lines.append("")
        return "\n".join(lines)

    async def run_invariant_test(
        self, sandbox_root: Path, rel_file_path: Path, void_name: str, invariant_code: str
    ) -> Tuple[bool, Optional[str]]:
        rustc_bin = shutil.which("rustc")
        if not rustc_bin:
            return True, None

        test_file = sandbox_root / f"_test_{void_name}.rs"
        full_code = (sandbox_root / rel_file_path).read_text(encoding="utf-8")
        test_file.write_text(f"{full_code}\n\nfn main() {{\n{invariant_code}\n}}\n", encoding="utf-8")
        try:
            proc = await asyncio.create_subprocess_exec(
                rustc_bin, str(test_file), "--out-dir", str(sandbox_root),
                stdout=asyncio.subprocess.PIPE, stderr=asyncio.subprocess.PIPE
            )
            _, stderr = await proc.communicate()
            if proc.returncode != 0:
                return False, stderr.decode("utf-8", errors="replace")
            return True, None
        finally:
            test_file.unlink(missing_ok=True)

    def build_auto_invariant_prompt(self, void_name: str, attributes: Dict[str, Any]) -> List[Dict[str, str]]:
        return [
            {"role": "system", "content": "Write Rust assert! statement."},
            {"role": "user", "content": f"Test {void_name}"},
        ]
