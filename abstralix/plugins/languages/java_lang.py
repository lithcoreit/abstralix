from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple
from abstralix.plugins.languages.base import BaseLanguagePlugin


class JavaLanguagePlugin(BaseLanguagePlugin):
    language_id = "java"

    def build_prompt(
        self, void_name: str, attributes: Dict[str, Any], dependencies_info: List[Dict[str, Any]], error_feedback: Optional[str] = None
    ) -> List[Dict[str, str]]:
        in_params = attributes.get("@in") or {}
        out_params = attributes.get("@out") or {}
        ret = list(out_params.values())[0] if len(out_params) == 1 else "void"
        args = ", ".join(f"{v} {k}" for k, v in in_params.items())
        sig = f"public static {ret} {void_name}({args})"
        return [
            {"role": "system", "content": "Write ONLY the Java method. No markdown fences."},
            {"role": "user", "content": f"Signature: {sig}\nContext: {attributes.get('@context')}"},
        ]

    def check_syntax(self, code: str, void_name: str) -> Tuple[bool, Optional[str]]:
        if void_name not in code:
            return False, f"Method '{void_name}' not found"
        return True, None

    def assemble_file(
        self, file_attributes: Dict[str, Any], voids_code: List[str], cross_file_imports: List[Tuple[str, str]]
    ) -> str:
        lines = ["// Generated by Abstralix 0.5.0", "public class Main {"]
        for v in voids_code:
            for l in v.strip().splitlines():
                lines.append(f"    {l}")
            lines.append("")
        lines.append("}")
        return "\n".join(lines)

    async def run_invariant_test(
        self, sandbox_root: Path, rel_file_path: Path, void_name: str, invariant_code: str
    ) -> Tuple[bool, Optional[str]]:
        return True, None

    def build_auto_invariant_prompt(self, void_name: str, attributes: Dict[str, Any]) -> List[Dict[str, str]]:
        return [{"role": "system", "content": "Test Java"}, {"role": "user", "content": f"Test {void_name}"}]


class CSharpLanguagePlugin(JavaLanguagePlugin):
    language_id = "csharp"
