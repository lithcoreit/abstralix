async def test_single_language(lang_id: str, plugin: Any) -> Tuple[bool, str]:
    if lang_id not in FIXTURES:
        return False, f"Missing test fixture for '{lang_id}'"

    fix = FIXTURES[lang_id]
    void_name = "test_fn"
    attrs = {
        "@context": "Double the input integer",
        "@in": {"x": "int"},
        "@out": {"result": "int"},
    }

    # 1. Тест build_prompt
    try:
        msgs = plugin.build_prompt(
            void_name=void_name,
            attributes=attrs,
            dependencies_info=[],
            error_feedback=None,
        )
        if not isinstance(msgs, list) or len(msgs) < 2:
            return False, "build_prompt returned invalid messages structure"
    except Exception as exc:
        return False, f"build_prompt crashed: {exc}"

    # 2. Тест check_syntax на валидном коде
    try:
        ok_valid, err_valid = plugin.check_syntax(fix["valid"], void_name)
        if not ok_valid:
            return False, f"Rejected valid code: {err_valid}"
    except Exception as exc:
        return False, f"check_syntax(valid) crashed: {exc}"

    # 3. Тест check_syntax на битом коде
    try:
        ok_inv, _ = plugin.check_syntax(fix["invalid"], void_name)
        if ok_inv:
            return False, "Accepted invalid code as valid (syntax checker too loose)"
    except Exception as exc:
        return False, f"check_syntax(invalid) crashed: {exc}"

    # 4. Тест assemble_file
    try:
        assembled = plugin.assemble_file(
            file_attributes={"@lib": ["math"]},
            voids_code=[fix["valid"]],
            cross_file_imports=[],
        )
        if not assembled or not isinstance(assembled, str):
            return False, "assemble_file returned empty or non-string output"
    except Exception as exc:
        return False, f"assemble_file crashed: {exc}"

    # 5. Тест run_invariant_test в изолированной песочнице
    try:
        with tempfile.TemporaryDirectory() as tmp_dir:
            tmp_path = Path(tmp_dir)
            target_file = tmp_path / f"test_module{fix['file_ext']}"
            target_file.write_text(assembled, encoding="utf-8")

            test_ok, test_err = await plugin.run_invariant_test(
                sandbox_root=tmp_path,
                rel_file_path=Path(target_file.name),
                void_name=void_name,
                invariant_code=fix["inv_code"],
            )
            # Для Python тест обязан пройти реально
            if lang_id == "python" and not test_ok:
                return False, f"Python invariant test failed: {test_err}"
    except Exception as exc:
        return False, f"run_invariant_test crashed with exception: {exc}"

    return True, "All 5 contracts OK"


async def main():
    console.print("\n[bold cyan]Abstralix 0.5.0 Language Plugins Verification Harness[/bold cyan]\n")

    reg = PluginRegistry()
    languages = reg.languages

    table = Table(show_header=True, header_style="bold magenta", show_lines=False)
    table.add_column("Language ID", style="cyan", width=15)
    table.add_column("Plugin Class", style="white", width=28)
    table.add_column("Status", width=12)
    table.add_column("Diagnostics / Notes", style="dim white")

    passed_count = 0
    total_count = len(languages)

    for lang_id, plugin in sorted(languages.items()):
        is_ok, message = await test_single_language(lang_id, plugin)
        if is_ok:
            passed_count += 1
            table.add_row(lang_id, plugin.__class__.__name__, "[bold green]PASS[/bold green]", message)
        else:
            table.add_row(lang_id, plugin.__class__.__name__, "[bold red]FAIL[/bold red]", message)

    console.print(table)
    console.print()

    if passed_count == total_count:
        console.print(f"[bold green]✓ 100% SUCCESS:[/bold green] All {total_count} language plugins are fully operational!\n")
    else:
        console.print(f"[bold yellow]![/bold yellow] {passed_count}/{total_count} passed. Check failed plugins above.\n")


if __name__ == "__main__":
    asyncio.run(main())
